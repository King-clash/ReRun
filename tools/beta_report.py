"""Checklist for taking the BETA scripts live: which templates each still lacks, and what to record.

    py tools/beta_report.py          prints the report and writes BETA_CHECKLISTS.md

A script is BETA until it has run on the real game. For each one this lists the pictures it needs
(captured vs missing in templates/), then a short, identical procedure for the live check."""
from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from rerun.scripts import SCRIPTS  # noqa: E402
from rerun.vision import TemplateStore  # noqa: E402

PROCEDURE = """1. Capture the missing required pictures in the Templates tab (game on the right screen each time).
2. Put the game where the script's instructions say, set a SMALL limit (1-2 runs / a few minutes), press Start.
3. Watch the Log. Success = the first full cycle completes and the script stops or loops as described.
4. If it stops or sits: copy the exact Log/Discord message (it now names the closest known screens) and the
   saved frame in `debug/`; do not retry blindly.
5. When it works: save 1-2 real screenshots as `tests/fixtures/<script>_<screen>.png` and tell Claude so the
   script can lose its BETA label and gain a real-screen test."""


def main() -> int:
    store = TemplateStore(ROOT / "templates")
    beta = [c for c in SCRIPTS.values() if c.BETA]
    lines = ["# BETA script checklists", "",
             f"Generated by `py tools/beta_report.py` on {time.strftime('%Y-%m-%d')}. "
             f"{len(beta)} scripts have never run on the real game.", "",
             "## Same procedure for every script", "", PROCEDURE, ""]
    summary = ["| Script | Required pictures | Missing | Optional missing |", "|---|---:|---:|---:|"]
    detail = []
    for cls in sorted(beta, key=lambda c: c.NAME):
        req = [t for t in cls.all_templates() if not t.optional]
        opt = [t for t in cls.all_templates() if t.optional]
        miss_req = [t for t in req if not store.has(t.name)]
        miss_opt = [t for t in opt if not store.has(t.name)]
        summary.append(f"| {cls.NAME} | {len(req)} | {len(miss_req)} | {len(miss_opt)} |")
        d = [f"### {cls.NAME} (`{cls.ID}`)", "", cls.DESCRIPTION or "", ""]
        if miss_req:
            d += ["Missing required pictures (the script refuses to start without them):", ""]
            d += [f"- `{t.name}` - {t.description}" for t in miss_req]
        else:
            d += ["All required pictures are captured."]
        if miss_opt:
            d += ["", "Missing optional pictures (features that need them stay off):", ""]
            d += [f"- `{t.name}`" for t in miss_opt[:12]] + ([f"- ...and {len(miss_opt) - 12} more"] if len(miss_opt) > 12 else [])
        detail.append("\n".join(d) + "\n")
    text = "\n".join(lines + ["## Summary", ""] + summary + [""] + detail)
    (ROOT / "BETA_CHECKLISTS.md").write_text(text, encoding="utf-8", newline="\n")
    print("\n".join(summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
